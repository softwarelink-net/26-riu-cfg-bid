function json(data: unknown, status = 200): Response {
  return new Response(JSON.stringify(data), {
    status,
    headers: {
      'Content-Type': 'application/json; charset=utf-8',
      ...CORS_HEADERS,
    },
  })
}

function crc32(bytes: Uint8Array): string {
  let crc = 0xffffffff
  for (let i = 0; i < bytes.length; i++) {
    crc ^= bytes[i]
    for (let j = 0; j < 8; j++) {
      crc = (crc >>> 1) ^ (crc & 1 ? 0xedb88320 : 0)
    }
  }
  return ((crc ^ 0xffffffff) >>> 0).toString(16).padStart(8, '0').toUpperCase()
}

async function sha256Hex(bytes: Uint8Array): Promise<string> {
  const digest = await crypto.subtle.digest('SHA-256', bytes)
  return [...new Uint8Array(digest)].map((b) => b.toString(16).padStart(2, '0')).join('')
}

function parseAuth(request: Request): SessionUser | null {
  const header = request.headers.get('Authorization')
  if (!header?.startsWith('Bearer ')) return null
  try {
    const payload = JSON.parse(utf8FromBase64(header.slice(7)))
    if (!payload?.id || !payload?.role) return null
    return payload as SessionUser
  } catch {
    return null
  }
}

function utf8ToBase64(str: string): string {
  const bytes = new TextEncoder().encode(str)
  let binary = ''
  bytes.forEach((b) => {
    binary += String.fromCharCode(b)
  })
  return btoa(binary)
}

function utf8FromBase64(b64: string): string {
  const binary = atob(b64)
  const bytes = new Uint8Array(binary.length)
  for (let i = 0; i < binary.length; i++) bytes[i] = binary.charCodeAt(i)
  return new TextDecoder().decode(bytes)
}

function encodeToken(user: SessionUser): string {
  return utf8ToBase64(JSON.stringify(user))
}

async function writeAudit(
  env: Env,
  userId: string | null,
  action: string,
  request: Request,
  payload: unknown = null,
) {
  const ip = request.headers.get('CF-Connecting-IP') || request.headers.get('X-Forwarded-For') || '127.0.0.1'
  await env.DB.prepare(
    'INSERT INTO audit_logs (user_id, action, ip_address, payload) VALUES (?, ?, ?, ?)',
  )
    .bind(userId, action, ip, payload ? JSON.stringify(payload) : null)
    .run()
}

function generateHeader(configName: string, busType: string, channels: ChannelInput[]): string {
  const guard = configName.toUpperCase().replace(/[^A-Z0-9]/g, '_') + '_H'
  const defs = channels
    .map(
      (ch, i) =>
        `  /* CH${i}: ${ch.label} */\n` +
        `  #define RIU_CH${i}_LABEL        "${ch.label}"\n` +
        `  #define RIU_CH${i}_BAUD         (${ch.baudRate}U)\n` +
        `  #define RIU_CH${i}_PARITY       (${ch.parity === 'ODD' ? 1 : ch.parity === 'EVEN' ? 2 : 0}U)\n` +
        `  #define RIU_CH${i}_FRAME_LEN    (${ch.frameLength}U)\n` +
        `  #define RIU_CH${i}_CYCLE_MS     (${ch.cycleMs}U)`,
    )
    .join('\n\n')

  return `/**
 * Autogenerated RIU ICD Header — DO NOT EDIT
 * Config : ${configName}
 * Bus    : ${busType}
 * Model  : Zero-malloc static memory, MISRA-C oriented
 */
#ifndef ${guard}
#define ${guard}

#include <stdint.h>

#define RIU_CHANNEL_COUNT (${channels.length}U)
#define RIU_BUS_TYPE_${busType} 1

${defs}

typedef struct {
  uint16_t channel_id;
  uint32_t baud_rate;
  uint8_t  parity;
  uint16_t frame_len;
  uint16_t cycle_ms;
} riu_channel_cfg_t;

extern const riu_channel_cfg_t g_riu_channels[RIU_CHANNEL_COUNT];
uint32_t riu_parse_frame(const uint8_t *buf, uint16_t len, uint16_t channel_id);

#endif /* ${guard} */
`
}

function generateSource(configName: string, busType: string, channels: ChannelInput[]): string {
  const table = channels
    .map(
      (ch, i) =>
        `  { ${i}U, ${ch.baudRate}U, ${ch.parity === 'ODD' ? 1 : ch.parity === 'EVEN' ? 2 : 0}U, ${ch.frameLength}U, ${ch.cycleMs}U }`,
    )
    .join(',\n')

  return `/**
 * Autogenerated RIU Parser Source — DO NOT EDIT
 * Config : ${configName}
 * Bus    : ${busType}
 * Constraint: no dynamic allocation (malloc-free)
 */
#include "riu_config.h"

const riu_channel_cfg_t g_riu_channels[RIU_CHANNEL_COUNT] = {
${table}
};

uint32_t riu_parse_frame(const uint8_t *buf, uint16_t len, uint16_t channel_id)
{
  uint32_t word = 0U;
  uint16_t i;

  if ((buf == 0) || (channel_id >= RIU_CHANNEL_COUNT)) {
    return 0U;
  }
  if (len < g_riu_channels[channel_id].frame_len) {
    return 0U;
  }

  for (i = 0U; i < g_riu_channels[channel_id].frame_len; i++) {
    word = (word << 8) | (uint32_t)buf[i];
  }
  return word;
}
`
}

interface ChannelInput {
  label: string
  baudRate: number
  parity: 'NONE' | 'ODD' | 'EVEN'
  frameLength: number
  cycleMs: number
}

function buildBinaryPayload(
  flashAddress: string,
  busType: string,
  channels: ChannelInput[],
): Uint8Array {
  const header = new Uint8Array(16)
  const addr = parseInt(flashAddress.replace(/^0x/i, ''), 16) || 0x08000000
  header[0] = 0x52 // R
  header[1] = 0x49 // I
  header[2] = 0x55 // U
  header[3] = 0x01 // version
  header[4] = (addr >>> 24) & 0xff
  header[5] = (addr >>> 16) & 0xff
  header[6] = (addr >>> 8) & 0xff
  header[7] = addr & 0xff
  header[8] = busType === 'ARINC429' ? 1 : busType === 'MIL_STD_1553B' ? 2 : busType === 'AFDX' ? 3 : 4
  header[9] = channels.length & 0xff
  header[10] = 0xaa
  header[11] = 0x55

  const body = new Uint8Array(channels.length * 12)
  channels.forEach((ch, idx) => {
    const o = idx * 12
    body[o] = idx & 0xff
    body[o + 1] = ch.parity === 'ODD' ? 1 : ch.parity === 'EVEN' ? 2 : 0
    body[o + 2] = (ch.baudRate >>> 8) & 0xff
    body[o + 3] = ch.baudRate & 0xff
    body[o + 4] = (ch.frameLength >>> 8) & 0xff
    body[o + 5] = ch.frameLength & 0xff
    body[o + 6] = (ch.cycleMs >>> 8) & 0xff
    body[o + 7] = ch.cycleMs & 0xff
    body[o + 8] = 0xde
    body[o + 9] = 0xad
    body[o + 10] = 0xbe
    body[o + 11] = 0xef
  })

  const out = new Uint8Array(header.length + body.length + 4)
  out.set(header, 0)
  out.set(body, header.length)
  const crc = crc32(out.subarray(0, out.length - 4))
  const crcVal = parseInt(crc, 16)
  out[out.length - 4] = (crcVal >>> 24) & 0xff
  out[out.length - 3] = (crcVal >>> 16) & 0xff
  out[out.length - 2] = (crcVal >>> 8) & 0xff
  out[out.length - 1] = crcVal & 0xff
  return out
}

function toHexDump(bytes: Uint8Array, baseAddr = 0x08000000): string {
  const lines: string[] = []
  for (let i = 0; i < bytes.length; i += 16) {
    const slice = bytes.subarray(i, Math.min(i + 16, bytes.length))
    const hex = [...slice].map((b) => b.toString(16).padStart(2, '0').toUpperCase()).join(' ')
    const ascii = [...slice].map((b) => (b >= 32 && b < 127 ? String.fromCharCode(b) : '.')).join('')
    lines.push(`${(baseAddr + i).toString(16).padStart(8, '0').toUpperCase()}  ${hex.padEnd(47, ' ')}  |${ascii}|`)
  }
  return lines.join('\n')
}

