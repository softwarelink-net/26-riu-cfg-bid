async function handleApi(request: Request, env: Env, url: URL): Promise<Response> {
  const path = url.pathname.replace(/\/+$/, '') || '/'
  const method = request.method.toUpperCase()
  const user = parseAuth(request)

  if (method === 'OPTIONS') {
    return new Response(null, { status: 204, headers: CORS_HEADERS })
  }

  // Auth
  if (path === '/api/auth/login' && method === 'POST') {
    const body = (await request.json()) as { email?: string; password?: string }
    const email = (body.email || '').trim().toLowerCase()
    const password = body.password || ''
    if (!DEMO_CREDENTIALS[email] || DEMO_CREDENTIALS[email] !== password) {
      return json({ ok: false, error: '邮箱或密码错误' }, 401)
    }
    const row = await env.DB.prepare('SELECT id, email, display_name, role FROM users WHERE email = ?')
      .bind(email)
      .first<SessionUser>()
    if (!row) return json({ ok: false, error: '用户不存在' }, 404)
    const token = encodeToken(row)
    await writeAudit(env, row.id, 'AUTH_LOGIN', request, { email })
    return json({ ok: true, token, user: row })
  }

  if (path === '/api/auth/me' && method === 'GET') {
    if (!user) return json({ ok: false, error: '未登录' }, 401)
    return json({ ok: true, user })
  }

  if (path === '/api/auth/logout' && method === 'POST') {
    await writeAudit(env, user?.id || null, 'AUTH_LOGOUT', request)
    return json({ ok: true })
  }

  // Tender
  if (path === '/api/tender' && method === 'GET') {
    const tender = await env.DB.prepare('SELECT * FROM tender_items ORDER BY publish_time DESC LIMIT 1').first()
    if (!tender) return json({ ok: false, error: '未找到招标公告' }, 404)

    const deadline = new Date(String(tender.deadline).replace(' ', 'T') + '+08:00').getTime()
    const now = Date.now()
    const remainMs = Math.max(0, deadline - now)

    const qualifications = [
      { id: 'q1', label: '2025年度审计报告', required: true, status: 'PENDING', note: '需加盖公章扫描件' },
      { id: 'q2', label: 'CA数字证书办理流程', required: true, status: 'PENDING', note: '龙集采平台认证' },
      { id: 'q3', label: '非失信被执行人证明', required: true, status: 'PENDING', note: '法院公开查询截图' },
      { id: 'q4', label: '航空软件研发业绩', required: true, status: 'OPTIONAL', note: '同类RIU/ICD项目优先' },
      { id: 'q5', label: '保密资质/人员备案', required: false, status: 'OPTIONAL', note: '按招标文件要求提交' },
    ]

    return json({
      ok: true,
      tender,
      countdown: {
        deadline: tender.deadline,
        remainMs,
        remainDays: Math.floor(remainMs / 86400000),
        remainHours: Math.floor((remainMs % 86400000) / 3600000),
        remainMinutes: Math.floor((remainMs % 3600000) / 60000),
        remainSeconds: Math.floor((remainMs % 60000) / 1000),
        isExpired: remainMs <= 0,
      },
      qualifications,
      contacts: [
        { role: '招标代理', name: '中航招采科技（北京）有限公司', phone: '010-XXXX-8801', email: 'riu-bid@avic-demo.example' },
        { role: '技术咨询', name: '西安航空计算技术研究所项目组', phone: '029-XXXX-6610', email: 'riu-tech@xac-demo.example' },
      ],
      milestones: [
        { day: 30, title: '详细设计完成', desc: 'ICD元模型与生成器架构锁定' },
        { day: 45, title: '软硬件完成', desc: 'PC工具与Flash镜像链路闭环' },
        { day: 60, title: '调试与最终交付', desc: '联合编译验证与验收交付' },
      ],
    })
  }

  // RIU templates
  if (path === '/api/riu/templates' && method === 'GET') {
    return json({ ok: true, templates: ICD_TEMPLATES })
  }

  // RIU generate
  if (path === '/api/riu/generate' && method === 'POST') {
    if (user && user.role === 'GUEST') {
      return json({ ok: false, error: '访客仅可预览，不可生成' }, 403)
    }
    // Allow unauthenticated read-only validation? PRD says GUEST Read-Only Preview.
    // Generation for AUDITOR = validation, AVIONICS_ADMIN = full. Allow guest? No.
    // But for demo UX, allow generate for auditor+admin; guest gets 403.
    // If no user, treat as GUEST.
    if (!user) {
      return json({ ok: false, error: '请登录后执行生成。访客仅可预览模板。' }, 401)
    }

    const body = (await request.json()) as {
      config_name?: string
      version?: string
      target_bus_type?: string
      flash_address_hex?: string
      channels?: ChannelInput[]
      persist?: boolean
    }

    const configName = body.config_name || 'riu_config'
    const version = body.version || '1.0.0'
    const busType = (body.target_bus_type || 'ARINC429') as string
    const flashAddress = body.flash_address_hex || '0x08010000'
    const channels = (body.channels && body.channels.length ? body.channels : ICD_TEMPLATES[0].channels) as ChannelInput[]

    const hCode = generateHeader(configName, busType, channels)
    const cCode = generateSource(configName, busType, channels)
    const binary = buildBinaryPayload(flashAddress, busType, channels)
    const crc = crc32(binary)
    const sha = await sha256Hex(binary)
    const hexDump = toHexDump(binary, parseInt(flashAddress.replace(/^0x/i, ''), 16) || 0x08010000)

    let savedId: string | null = null
    if (body.persist && user.role === 'AVIONICS_ADMIN') {
      savedId = `riu_${Date.now().toString(36)}`
      await env.DB.prepare(
        `INSERT INTO riu_configurations
         (id, config_name, version, target_bus_type, flash_address_hex, binary_size_bytes, crc32_checksum, generated_c_code, generated_h_code, created_by)
         VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
      )
        .bind(savedId, configName, version, busType, flashAddress, binary.length, crc, cCode, hCode, user.id)
        .run()

      try {
        await env.STORAGE.put(`riu/${savedId}.bin`, binary, {
          httpMetadata: { contentType: 'application/octet-stream' },
          customMetadata: { crc32: crc, sha256: sha },
        })
      } catch {
        // R2 may be unavailable in some local setups; ignore storage failure for demo
      }
    }

    await writeAudit(env, user.id, 'RIU_GENERATE', request, {
      configName,
      busType,
      size: binary.length,
      crc,
      persist: Boolean(body.persist),
    })

    return json({
      ok: true,
      result: {
        id: savedId,
        config_name: configName,
        version,
        target_bus_type: busType,
        flash_address_hex: flashAddress,
        binary_size_bytes: binary.length,
        crc32_checksum: crc,
        sha256_checksum: sha,
        generated_h_code: hCode,
        generated_c_code: cCode,
        hex_dump: hexDump,
        binary_base64: btoa(String.fromCharCode(...binary)),
        misra_notes: [
          '无动态内存分配 (malloc-free)',
          '固定长度通道表 g_riu_channels[]',
          '空指针与边界检查完整',
          'uintN_t 定宽整数',
        ],
      },
    })
  }

  // Verify artifact
  if (path === '/api/riu/verify' && method === 'POST') {
    const body = (await request.json()) as { binary_base64?: string; expected_crc32?: string }
    if (!body.binary_base64) return json({ ok: false, error: '缺少 binary_base64' }, 400)
    const raw = Uint8Array.from(atob(body.binary_base64), (c) => c.charCodeAt(0))
    const crc = crc32(raw)
    const sha = await sha256Hex(raw)
    const match = body.expected_crc32 ? body.expected_crc32.toUpperCase() === crc : true
    await writeAudit(env, user?.id || null, 'RIU_VERIFY', request, { crc, match })
    return json({ ok: true, crc32: crc, sha256: sha, match, size: raw.length })
  }

  // System configs
  if (path === '/api/system/configs' && method === 'GET') {
    if (!user || (user.role !== 'AUDITOR' && user.role !== 'AVIONICS_ADMIN')) {
      return json({ ok: false, error: '权限不足' }, 403)
    }
    const { results } = await env.DB.prepare('SELECT * FROM system_configs ORDER BY is_feature_flag DESC, config_key').all()
    return json({ ok: true, configs: results })
  }

  if (path === '/api/system/configs' && method === 'PUT') {
    if (!user || user.role !== 'AVIONICS_ADMIN') {
      return json({ ok: false, error: '仅 AVIONICS_ADMIN 可修改' }, 403)
    }
    const body = (await request.json()) as { config_key: string; config_value: string }
    await env.DB.prepare(
      'UPDATE system_configs SET config_value = ?, updated_at = CURRENT_TIMESTAMP WHERE config_key = ?',
    )
      .bind(body.config_value, body.config_key)
      .run()
    await writeAudit(env, user.id, 'CONFIG_UPDATE', request, body)
    return json({ ok: true })
  }

  // Audit logs
  if (path === '/api/audit/logs' && method === 'GET') {
    if (!user || (user.role !== 'AUDITOR' && user.role !== 'AVIONICS_ADMIN')) {
      return json({ ok: false, error: '权限不足' }, 403)
    }
    const { results } = await env.DB.prepare(
      'SELECT * FROM audit_logs ORDER BY timestamp DESC LIMIT 100',
    ).all()
    return json({ ok: true, logs: results })
  }

  // Health
  if (path === '/api/health' && method === 'GET') {
    let dbOk = false
    try {
      await env.DB.prepare('SELECT 1').first()
      dbOk = true
    } catch {
      dbOk = false
    }
    return json({
      ok: true,
      service: '26-riu-cfg-bid',
      db: dbOk ? 'up' : 'down',
      host: env.DEPLOYMENT_HOST,
      ts: new Date().toISOString(),
    })
  }

  // Saved RIU configs list
  if (path === '/api/riu/configs' && method === 'GET') {
    if (!user || (user.role !== 'AUDITOR' && user.role !== 'AVIONICS_ADMIN')) {
      return json({ ok: false, error: '权限不足' }, 403)
    }
    const { results } = await env.DB.prepare(
      'SELECT id, config_name, version, target_bus_type, flash_address_hex, binary_size_bytes, crc32_checksum, created_by, created_at FROM riu_configurations ORDER BY created_at DESC LIMIT 50',
    ).all()
    return json({ ok: true, configs: results })
  }

  return json({ ok: false, error: `Unknown API route: ${method} ${path}` }, 404)
}

function siteIdFromHost(hostname: string, rootDomain: string): string {
  const host = hostname.toLowerCase()
  const root = rootDomain.toLowerCase()
  if (host === root) return '_root'
  if (host === `www.${root}`) return 'www'
  if (host.endsWith(`.${root}`)) return host.slice(0, -(root.length + 1))
  return host
}

function isRiuHost(hostname: string, env: Env): boolean {
  const host = hostname.toLowerCase()
  const root = (env.ROOT_DOMAIN || 'softwarelink.net').toLowerCase()
  const slug = (env.PROJECT_SLUG || '26-riu-cfg-bid').toLowerCase()
  return host === `${slug}.${root}` || host.startsWith(`${slug}.`)
}

function contentTypeFor(path: string): string {
  const ext = path.split('.').pop()?.toLowerCase() || ''
  const map: Record<string, string> = {
    html: 'text/html; charset=utf-8',
    js: 'application/javascript; charset=utf-8',
    css: 'text/css; charset=utf-8',
    json: 'application/json; charset=utf-8',
    svg: 'image/svg+xml',
    png: 'image/png',
    jpg: 'image/jpeg',
    jpeg: 'image/jpeg',
    webp: 'image/webp',
    ico: 'image/x-icon',
    txt: 'text/plain; charset=utf-8',
    map: 'application/json',
    xml: 'application/xml; charset=utf-8',
    woff: 'font/woff',
    woff2: 'font/woff2',
  }
  return map[ext] || 'application/octet-stream'
}

